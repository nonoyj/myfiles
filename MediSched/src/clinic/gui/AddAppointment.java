    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed

        try {
        // Collect input from the interface
        String name   = jTextField1.getText().trim();
        String phone  = jTextField2.getText().trim();
        String reason = jTextArea1.getText().trim();

        // Auto date and time
        String date = new SimpleDateFormat("yyyy-MM-dd").format(new Date());
        String time = new SimpleDateFormat("HH:mm:ss").format(new Date());

        Appointment appt = new Appointment(name, phone, date, time, reason, Appointment.STATUS_PENDING);
        appt.validate();
        
        int confirm = JOptionPane.showConfirmDialog(this,
            appt.getSummary() + "\n\nSave this appointment?",
            "Confirm Appointment",
            JOptionPane.YES_NO_OPTION);

        if (confirm != JOptionPane.YES_OPTION) return;

        // DB insert using encapsulated getters
        try (Connection conn = DBConnection.getConnection();
             PreparedStatement pst = conn.prepareStatement(
                "INSERT INTO appointments(patient_name, phone, app_date, app_time, reason, status, added_by, updated_by) " +
                "VALUES (?,?,?,?,?,?,?,?)")) {

            pst.setString(1, appt.getName());
            pst.setString(2, appt.getPhone());
            pst.setString(3, appt.getDate());
            pst.setString(4, appt.getTime());
            pst.setString(5, appt.getReason());
            pst.setString(6, appt.getStatus());
            pst.setString(7, loggedInName);
            pst.setString(8, loggedInName);
            pst.executeUpdate();
        }

        JOptionPane.showMessageDialog(this, "Appointment Saved Successfully!");
        jButton1ActionPerformed(evt); // reuse clear button

    } catch (IllegalArgumentException e) {
        // Validation message comes from the model setter
        JOptionPane.showMessageDialog(this, e.getMessage(),
            "Validation Error", JOptionPane.WARNING_MESSAGE);
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage(),
            "Database Error", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_jButton3ActionPerformed

