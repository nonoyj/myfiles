    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
try {
        String name     = full_name.getText().trim();
        String username = usern.getText().trim();
        String pass     = new String(password.getPassword()).trim();
        String selectedRole = role.getSelectedItem().toString();

        // Basic validation
        if (name.isEmpty() || username.isEmpty() || pass.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                "Please fill in all fields.",
                "Missing Input",
                JOptionPane.WARNING_MESSAGE);
            return;
        }

        if (pass.length() < 6) {
            JOptionPane.showMessageDialog(this,
                "Password must be at least 6 characters.",
                "Validation Error",
                JOptionPane.WARNING_MESSAGE);
            return;
        }

        // Use User model for validation
        User newUser = new User(name, username, pass);
        newUser.validate();

        int confirm = JOptionPane.showConfirmDialog(this,
            newUser.getSummary() + "\n\nCreate this account?",
            "Confirm Account Creation",
            JOptionPane.YES_NO_OPTION);

        if (confirm != JOptionPane.YES_OPTION) return;

        // Decide which table to insert into
        String table = selectedRole.equals("Admin") ? "admin" : "user";

        try (Connection conn = DBConnection.getConnection();
             PreparedStatement pst = conn.prepareStatement(
                "INSERT INTO " + table + " (name, username, pass) VALUES (?, ?, ?)")) {

            pst.setString(1, newUser.getName());
            pst.setString(2, newUser.getUsername());
            pst.setString(3, newUser.getPassword());
            pst.executeUpdate();
        }

        JOptionPane.showMessageDialog(this,
            "Account created successfully as " + selectedRole + "!");
        jButton2ActionPerformed(evt); // clear fields

    } catch (IllegalArgumentException e) {
        JOptionPane.showMessageDialog(this, e.getMessage(),
            "Validation Error", JOptionPane.WARNING_MESSAGE);
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage(),
            "Database Error", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_jButton1ActionPerformed

