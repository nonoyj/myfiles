    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        int row = jTable1.getSelectedRow();

        if (row == -1) {
            JOptionPane.showMessageDialog(this, "Select a record first!");
            return;
        }

        try {
            Connection conn = DBConnection.getConnection();

            int id = Integer.parseInt(jTable1.getValueAt(row, 0).toString());

            String sql = "DELETE FROM appointments WHERE id=?";
            PreparedStatement pst = conn.prepareStatement(sql);
            pst.setInt(1, id);

            pst.executeUpdate();

            JOptionPane.showMessageDialog(this, "Deleted successfully!");
            loadAppointments();

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
        int row = jTable1.getSelectedRow();
        if (row == -1) {
            JOptionPane.showMessageDialog(this, "Select a record first!");
            return;
        }

        try {
            int id = Integer.parseInt(jTable1.getValueAt(row, 0).toString());

            // Model validates input through setters
            Appointment appt = new Appointment(
                jTextField4.getText().trim(), //textbox form (read only)
                jTextField3.getText().trim(), //textbox form (read only)
                jLabel11.getText(),   // date (read-only, from label)
                jLabel12.getText(),   // time (read-only, from label)
                jTextArea2.getText().trim(), //text area form (read only)
                jComboBox1.getSelectedItem().toString()
            );
            appt.validate();

            try (Connection conn = DBConnection.getConnection();
                PreparedStatement pst = conn.prepareStatement(
                    "UPDATE appointments SET patient_name=?, phone=?, reason=?, status=?, updated_by=? WHERE id=?")) {

                pst.setString(1, appt.getName());
                pst.setString(2, appt.getPhone());
                pst.setString(3, appt.getReason());
                pst.setString(4, appt.getStatus());
                pst.setString(5, loggedInName);
                pst.setInt(6, id);
                pst.executeUpdate();
            }

            JOptionPane.showMessageDialog(this, "Updated successfully!");
            loadAppointments();

        } catch (IllegalArgumentException e) {
            JOptionPane.showMessageDialog(this, e.getMessage(),
                "Validation Error", JOptionPane.WARNING_MESSAGE);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error: " + e.getMessage(),
                "Database Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton4ActionPerformed

